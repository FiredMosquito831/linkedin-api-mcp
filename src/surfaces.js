export function findSurfaces({ status, group } = {}) {
  if (status !== undefined && !STATUSES.has(status)) {
    throw new RangeError(`Unknown status "${String(status)}"; expected one of ${[...STATUSES].join(', ')}`);
  }
  if (group !== undefined && !GROUPS.has(group)) {
    throw new RangeError(`Unknown group "${String(group)}"; expected one of ${[...GROUPS].join(', ')}`);
  }
  return SURFACES.filter(
    (surface) =>
      (status === undefined || surface.status === status) &&
      (group === undefined || surface.group === group),
  );
}
